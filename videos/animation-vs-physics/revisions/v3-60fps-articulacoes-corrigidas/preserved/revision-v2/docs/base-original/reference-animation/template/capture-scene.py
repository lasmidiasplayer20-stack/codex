def mask_for(f,c):
 hsv=cv2.cvtColor(f,cv2.COLOR_BGR2HSV);lo,hi=c['h'];m=cv2.inRange(hsv,np.array([lo,170,175]),np.array([hi,255,255]))
 if lo==0:m|=cv2.inRange(hsv,np.array([176,170,175]),np.array([180,255,255]))
 if c.get('hollow'):m[hsv[:,:,1]<190]=0
 return m

def arc_head(mask):
 yy,xx=np.where(mask>0)
 if len(xx)<80:return None
 ymin,ymax=int(yy.min()),int(yy.max());xmax=int(xx.max());rows=[]
 for y in range(ymin,min(H,ymin+max(12,int((ymax-ymin)*.72)))):
  xs=np.where(mask[y]>0)[0]
  if len(xs):rows.append([float(xs.max()),float(y)])
 if len(rows)<12:return None
 pts=np.array(rows);rng=np.random.default_rng(731);best=None
 for _ in range(180):
  a,b,c=pts[rng.choice(len(pts),3,replace=False)];matrix=2*np.array([b-a,c-a]);rhs=np.array([np.dot(b,b)-np.dot(a,a),np.dot(c,c)-np.dot(a,a)])
  if abs(np.linalg.det(matrix))<1:continue
  center=np.linalg.solve(matrix,rhs);r=float(np.linalg.norm(a-center))
  if not 5<r<190 or not xmax-r*2.3<center[0]<xmax or not ymin<center[1]<ymax:continue
  if mask[int(np.clip(center[1],0,H-1)),int(np.clip(center[0],0,W-1))]>0:continue
  error=np.abs(np.linalg.norm(pts-center,axis=1)-r);inliers=error<3.5;score=int(inliers.sum())-.06*r
  if inliers.sum()<max(10,len(pts)*.46):continue
  if best is None or score>best[0]:best=(score,center,r)
 if best is None:return None
 _,center,r=best;return [float(center[0]),float(center[1]),r*.86]

def detect(m,c,prev):
 candidates=[]
 if c.get('hollow'):
  thickness=float(cv2.distanceTransform(m,cv2.DIST_L2,5).max());cs=[]
  for factor in [1.4,3.2,5.5]:
   kernel=int(np.clip(thickness*factor,5,81))|1
   closed=cv2.morphologyEx(m,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(kernel,kernel)))
   contours,hierarchy=cv2.findContours(closed,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_SIMPLE)
   if hierarchy is not None:cs.extend(c for k,c in enumerate(contours)if hierarchy[0,k,3]>=0 and len(c)>=5)
  if cs:
   for contour in cs:
    area=cv2.contourArea(contour);per=cv2.arcLength(contour,True)
    if area<35 or per<=0:continue
    (x,y),(w,h),angle=cv2.fitEllipse(contour);circularity=4*np.pi*area/per**2
    if min(w,h)/max(w,h)<.45 or circularity<.68:continue
    r=(w+h)/4*1.20
    if not 4<r<190:continue
    score=r*2+circularity*12
    if prev:score-=min(450,math.hypot(x-prev['head'][0],y-prev['head'][1]))*.035
    candidates.append((score,x,y,r,w*1.20,h*1.20,angle))
  if not candidates or max(c[3]for c in candidates)<25:
   arc=arc_head(m)
   if arc:
    x,y,r=arc;candidates.append((500,x,y,r,r*2,r*2,0))
   # A bright impact can open the colored ring. Fit the remaining circular
   # arc rather than losing the whole character during the close shot.
   reduced=cv2.resize(m,(W//2,H//2),interpolation=cv2.INTER_AREA)
   circles=cv2.HoughCircles(cv2.GaussianBlur(reduced,(5,5),1),cv2.HOUGH_GRADIENT,1,18,param1=70,param2=14,minRadius=3,maxRadius=95)
   if circles is not None:
    for x,y,r in circles[0]*2:
     if m[int(np.clip(y,0,H-1)),int(np.clip(x,0,W-1))]>0:continue
     xx=np.clip(np.rint(x+np.cos(np.linspace(0,2*np.pi,80,endpoint=False))*r).astype(int),0,W-1);yy=np.clip(np.rint(y+np.sin(np.linspace(0,2*np.pi,80,endpoint=False))*r).astype(int),0,H-1)
     support=(cv2.dilate(m,np.ones((5,5),np.uint8))[yy,xx]>0).mean()
     if support<.70:continue
     score=r*.70+support*40
     if prev:score-=min(450,math.hypot(x-prev['head'][0],y-prev['head'][1]))*.035
     r*=.86
     candidates.append((score,float(x),float(y),float(r),float(r*2),float(r*2),0))
 else:
  n,lab,stats,_=cv2.connectedComponentsWithStats(m)
  for k in range(1,n):
   x,y,w,h,area=stats[k]
   if area<40 or w<7 or h<9:continue
   part=(lab[y:y+h,x:x+w]==k).astype(np.uint8);dist=cv2.distanceTransform(np.pad(part,1),cv2.DIST_L2,5);_,r,_,p=cv2.minMaxLoc(dist)
   if not 4<r<190:continue
   hx,hy=x+p[0]-1,y+p[1]-1
   outside=[]
   for a in np.linspace(0,2*np.pi,24,endpoint=False):
    px=int(np.clip(hx+np.cos(a)*r*1.35,0,W-1));py=int(np.clip(hy+np.sin(a)*r*1.35,0,H-1));outside.append(m[py,px]>0)
   if np.mean(outside)>.66:continue
   score=r*2-np.mean(outside)*10
   if prev:score-=min(450,math.hypot(hx-prev['head'][0],hy-prev['head'][1]))*.045
   candidates.append((score,hx,hy,r,r*2,r*2,0))
 if not candidates:return None
 _,x,y,r,hw,hh,ha=max(candidates)
 return {'head':[round(float(x),3),round(float(y),3)],'r':round(float(r),3),'headShape':[round(hw/2,3),round(hh/2,3),round(ha,2)]}

def fit_actor(f,m,head,prev):
 hx,hy=head['head'];r=head['r'];m=m.copy();cv2.circle(m,(round(hx),round(hy)),round(r*.88),255,-1)
 m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,np.ones((3,3),np.uint8));n,lab,stats,_=cv2.connectedComponentsWithStats(m);label=lab[int(np.clip(hy,0,H-1)),int(np.clip(hx,0,W-1))]
 if not label:return None
 selected=(lab==label).astype(np.uint8)*255
 x,y,w,h=stats[label,:4];x0=max(0,int(min(x,hx-r*9)));y0=max(0,int(min(y,hy-r*8)));x1=min(W,int(max(x+w,hx+r*9)));y1=min(H,int(max(y+h,hy+r*10)))
 crop=selected[y0:y1,x0:x1];scale=min(1,13/r)
 if scale<1:crop=cv2.resize(crop,(max(2,round(crop.shape[1]*scale)),max(2,round(crop.shape[0]*scale))),interpolation=cv2.INTER_NEAREST)
 origin=np.array([x0,y0]);local_head=(np.array(head['head'])-origin)*scale
 key=(tuple(np.round(local_head,2)),round(r*scale,2),hashlib.blake2b(crop.tobytes(),digest_size=12).digest())
 if key in CACHE:local=json.loads(json.dumps(CACHE[key]))
 else:
  local_prev=None
  if prev:
   convert=lambda p:((np.array(p)-origin)*scale).tolist()
   local_prev={**prev,'head':convert(prev['head']),'r':prev['r']*scale,'shoulder':convert(prev['shoulder']),'hip':convert(prev['hip']),'arms':[[convert(j)for j in a]for a in prev['arms']],'legs':[[convert(j)for j in a]for a in prev['legs']]}
  local=bones.graph_pose(crop,local_head.tolist(),r*scale,[0,0],local_prev);CACHE[key]=local
 pose=None
 if local:
  convert=lambda p:np.round(np.array(p)/scale+origin,3).tolist()
  pose={**local,'head':head['head'],'r':r,'shoulder':convert(local['shoulder']),'hip':convert(local['hip']),'arms':[[convert(j)for j in a]for a in local['arms']],'legs':[[convert(j)for j in a]for a in local['legs']]}
 if pose:pose.update(head);pose['quality']=1;return pose
 if prev:
  ratio=r/prev['r'];old=np.array(prev['head']);new=np.array(head['head']);convert=lambda p:np.round(new+(np.array(p)-old)*ratio,3).tolist()
  return {**head,'shoulder':convert(prev['shoulder']),'hip':convert(prev['hip']),'arms':[[convert(j)for j in a]for a in prev['arms']],'legs':[[convert(j)for j in a]for a in prev['legs']],'angle':prev['angle'],'quality':.3}
 # A close shot can hide the body. Complete the same named bone vocabulary.
 point=lambda x,y:[hx+x*r,hy+y*r]
 return {**head,'shoulder':point(0,1.3),'hip':point(0,3.5),'arms':[[point(-.6,2.3),point(-.4,3.5)],[point(.6,2.3),point(.4,3.5)]],'legs':[[point(-.7,5),point(-1.2,6.6)],[point(.7,5),point(1.2,6.6)]],'angle':0,'quality':.15}

def weapon(f,kind,head=None,radius=14):
 hsv=cv2.cvtColor(f,cv2.COLOR_BGR2HSV)
 if kind=='sword':m=cv2.inRange(hsv,np.array([67,95,110]),np.array([90,255,255]))
 elif kind=='knife':m=cv2.inRange(hsv,np.array([0,0,105]),np.array([180,105,235]))
 else:m=cv2.inRange(hsv,np.array([143,45,65]),np.array([179,235,255]))
 m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,np.ones((3,3),np.uint8));n,lab,stats,centers=cv2.connectedComponentsWithStats(m);choices=[]
 for k in range(1,n):
  x,y,w,h,area=stats[k]
  if area<10:continue
  pts=cv2.findNonZero((lab==k).astype(np.uint8));box=cv2.minAreaRect(pts);a,b=box[1];long,short=max(a,b),min(a,b)
  if long<(10 if kind=='knife'else 17) or long<short*2 or long>(1200 if kind=='mace'else 500):continue
  if kind=='sword' and long>150:continue
  if kind=='knife' and long>450:continue
  if kind=='mace'and short<2 and centers[k][1]>380:continue
  center=centers[k];distance=np.linalg.norm(center-np.array(head))if head else 0
  if head and distance>max(210 if kind=='mace'else 150,radius*(6 if kind=='mace'else 7)):continue
  points=pts[:,0,:].astype(float);mean=points.mean(axis=0);cov=np.cov(points.T);vals,vecs=np.linalg.eigh(cov);axis=vecs[:,np.argmax(vals)];projection=(points-mean)@axis
  p0=mean+axis*np.percentile(projection,2);p1=mean+axis*np.percentile(projection,98)
  if kind=='mace':
   gray=cv2.inRange(hsv,np.array([0,0,35]),np.array([180,110,220]))
   def metal(p):
    xx,yy=np.rint(p).astype(int);roi=gray[max(0,yy-25):min(H,yy+26),max(0,xx-25):min(W,xx+26)];return np.count_nonzero(roi)
   if metal(p1)>metal(p0):p0,p1=p1,p0
  elif head and np.linalg.norm(p0-head)<np.linalg.norm(p1-head):p0,p1=p1,p0
  score=long-distance*.18+min(area,120)*.08
  choices.append((score,{'kind':kind,'a':np.round(p0,2).tolist(),'b':np.round(p1,2).tolist(),'width':round(float(max(2,short)),2)}))
 return max(choices,key=lambda p:p[0])[1]if choices else None

def scene_props(f,t):
 hsv=cv2.cvtColor(f,cv2.COLOR_BGR2HSV);result=[]
 # Character antialiasing must not be classified as a piece of scenery.
 actors=np.zeros((H,W),np.uint8)
 for name,c in CAST.items():
  if name=='green' and t>40.95:continue
  if any(lo<=t<=hi for lo,hi in c['times']):actors|=mask_for(f,c)
 actors=cv2.dilate(actors,np.ones((5,5),np.uint8))
 # Palette components are exported only as bounding-box object parameters.
 specs=[('yellow',[20,130,155],[38,255,255]),('blood',[0,125,25],[7,255,205]),('flesh',[5,95,65],[26,245,240])]
 if t>42:specs.append(('ribs',[44,190,140],[74,255,255]))
 for kind,lo,hi in specs:
  m=cv2.inRange(hsv,np.array(lo),np.array(hi));m[actors>0]=0
  if kind=='blood':
   m|=cv2.inRange(hsv,np.array([170,125,25]),np.array([180,255,205]));m[actors>0]=0
  if kind=='yellow':m[f[:,:,0]>25]=0
  if kind=='flesh':m[cv2.dilate(cv2.inRange(hsv,np.array([20,130,155]),np.array([38,255,255])),np.ones((5,5),np.uint8))>0]=0
  m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,np.ones((3 if kind=='yellow'else 7,7),np.uint8));n,lab,stats,centers=cv2.connectedComponentsWithStats(m)
  items=[]
  for k in range(1,n):
   x,y,w,h,area=map(int,stats[k]);cx,cy=centers[k]
   if area<20 or w<5 or h<3 or cy<200:continue
   if kind=='blood'and(h>160 or w>600):continue
   if kind=='flesh'and h>100 and t<74:continue
   if kind=='ribs'and t<43 and(w<30 or h>w):continue
   item={'kind':kind,'x':x,'y':y,'w':w,'h':h,'area':area}
   if kind=='yellow' and w<h*4 and h>12:
    points=[]
    for row in range(y,min(H,y+int(h*.53))):
     xs=np.where(lab[row]==k)[0]
     if len(xs):points.append([float(xs.max()),float(row)])
    if len(points)>8:
     pts=np.array(points);px,py=pts.T;cx,cy,c0=np.linalg.lstsq(np.column_stack([2*px,2*py,np.ones(len(px))]),px*px+py*py,rcond=None)[0];radius=math.sqrt(max(1,c0+cx*cx+cy*cy));error=np.median(abs(np.hypot(px-cx,py-cy)-radius))
     if 5<radius<h*.9 and x-w*.4<cx<x+w*.5 and error<4:item['headCircle']=[round(cx,3),round(cy,3),round(radius,3)]
   items.append(item)
  result+=sorted(items,key=lambda q:q['area'],reverse=True)[:10]
 # Bed: red blanket plus white mattress and brown supports.
 if t<4.8 or 16.4<t<27 or t>84.5:
  patients=[o for o in result if o['kind']=='yellow'and o['w']<o['h']*4 and o['area']>250]
  if patients:
   main=max(patients,key=lambda o:o['area']);parts=[o for o in result if o['kind']=='yellow'and o['x']<main['x']+main['h']*.8 and o['y']+o['h']<=main['y']+main['h'] and o['y']>main['y']-main['h']]
   x=min(o['x']for o in parts);y=min(o['y']for o in parts);right=max(o['x']+o['w']for o in parts);bottom=max(o['y']+o['h']for o in parts);w,h=right-x,bottom-y
   patient={'kind':'yellow','x':x,'y':y,'w':w,'h':h,'area':sum(o['area']for o in parts)};points=[];yellow=cv2.inRange(hsv,np.array([20,130,155]),np.array([38,255,255]))
   for row in range(y,min(H,y+int(h*.53))):
    xs=np.where(yellow[row,x:min(W,right)]>0)[0]
    if len(xs):points.append([float(xs.max()+x),float(row)])
   if len(points)>8:
    pts=np.array(points);px,py=pts.T;cx,cy,c0=np.linalg.lstsq(np.column_stack([2*px,2*py,np.ones(len(px))]),px*px+py*py,rcond=None)[0];radius=math.sqrt(max(1,c0+cx*cx+cy*cy));error=np.median(abs(np.hypot(px-cx,py-cy)-radius))
    if 5<radius<h*.9 and x-w*.5<cx<x+w*.5 and error<5:patient['headCircle']=[round(cx,3),round(cy,3),round(radius,3)]
   result=[o for o in result if o not in parts]+[patient];bed={'kind':'bed','x':round(x-h*.15),'y':bottom,'w':max(180 if t<4.8 else 0,round(w*2.2)),'h':max(12,round(h*.40))};rows=np.where((hsv[:,:,2]<20).mean(axis=1)>.7)[0];rows=rows[rows>H*.42];floor=int(rows[0])if len(rows)else H+20;bed['legHeight']=max(bed['h']*.65,floor-bed['y']-bed['h']);result=[o for o in result if not(o['kind']=='blood'and o['x']>bed['x']and o['y']>=bed['y'])];result.append(bed)
   return result
  m=cv2.inRange(hsv,np.array([0,90,35]),np.array([8,255,235]))|cv2.inRange(hsv,np.array([170,90,35]),np.array([180,255,235]));m=cv2.morphologyEx(m,cv2.MORPH_CLOSE,np.ones((5,7),np.uint8));n,lab,stats,_=cv2.connectedComponentsWithStats(m)
  yellow=cv2.inRange(hsv,np.array([20,130,155]),np.array([38,255,255]))
  candidates=[]
  for x,y,w,h,area in stats[1:]:
   if w>45 and h>8 and w>h*2 and y>H*.30 and area>150:
    if np.count_nonzero(yellow[max(0,y-h*2):min(H,y+h//2),x:min(W,x+w)])>20:candidates.append((area,x,y,w,h))
  if candidates:
   _,x,y,w,h=max(candidates);result=[o for o in result if not(o['kind']=='blood'and x<=o['x']+o['w']/2<=x+w and y<=o['y']+o['h']/2<=y+h)];result.append({'kind':'bed','x':int(x),'y':int(y),'w':int(w),'h':int(h)})
 return result

def main():
 ap=argparse.ArgumentParser();ap.add_argument('video');ap.add_argument('--output',default='capture.json');ap.add_argument('--debug-dir');ap.add_argument('--only-actor');ap.add_argument('--base');a=ap.parse_args();cap=cv2.VideoCapture(a.video);fps=cap.get(cv2.CAP_PROP_FPS);tracks={k:[]for k in CAST};previous={};scenes=[];weapons=[];count=0
 if a.base:
  base=json.loads(Path(a.base).read_text());tracks=base['tracks'];scenes=base['scenes'];weapons=base['weapons']
  if a.only_actor:tracks[a.only_actor]=[]
 debug=Path(a.debug_dir)if a.debug_dir else None
 if debug:debug.mkdir(parents=True,exist_ok=True)
 while True:
  ok,original=cap.read()
  if not ok:break
  f=cv2.resize(original,(W,H),interpolation=cv2.INTER_AREA);t=count/fps;current={}
  for name,c in CAST.items():
   if a.only_actor and name!=a.only_actor:continue
   if not any(lo<=t<=hi for lo,hi in c['times']):continue
   m=mask_for(f,c);head=detect(m,c,previous.get(name));pose=fit_actor(f,m,head,previous.get(name))if head else None
   if pose:pose['t']=round(t,6);tracks[name].append(pose);previous[name]=pose;current[name]=pose
  if t>2.6 and not a.only_actor:
   active=[]
   for kind,name,lo,hi in [('sword','red',2.6,17),('sword',None,39,94),('knife','green',17,43),('mace','red',37.7,87)]:
    if lo<t<hi:
     v=weapon(f,kind,current.get(name,{}).get('head'))
     if v:active.append(v)
   weapons.append({'t':round(t,6),'objects':active})
  if count%6==0 and not a.only_actor:
   bg=np.median(f[10:170,100:850].reshape(-1,3),axis=0)[::-1];v=cv2.cvtColor(f,cv2.COLOR_BGR2HSV)[:,:,2];dark=(v[:,20:940]<20).mean(axis=1);rows=np.where(dark>.70)[0];rows=rows[rows>H*.42];floor=int(rows[0])if len(rows)else H+20
   scenes.append({'t':round(t,6),'color':np.rint(bg).astype(int).tolist(),'floor':floor,'props':scene_props(f,t)if t>2.6 else []})
  if debug and count%120==0:
   overlay=f.copy()
   for name,p in current.items():
    cv2.circle(overlay,tuple(np.rint(p['head']).astype(int)),round(p['r']),(255,255,255),1)
    for attachment,limbs in [(p['shoulder'],p['arms']),(p['hip'],p['legs'])]:
     for limb in limbs:cv2.polylines(overlay,[np.rint([attachment,*limb]).astype(np.int32)],False,(255,110,200),1,cv2.LINE_AA)
   cv2.imwrite(str(debug/f'capture-{t:.2f}.jpg'),overlay)
  if count%240==0:print('Frame',count,flush=True)
  count+=1
 cap.release();result={'fps':fps,'frames':count,'duration':count/fps,'width':W,'height':H,'cast':CAST,'tracks':tracks,'scenes':scenes,'weapons':weapons,'method':'Offline named joints and typed geometric prop parameters; no bitmap or free contour assets'};result['mediaDuration']=float(json.loads(subprocess.check_output(['ffprobe','-v','error','-show_format','-of','json',a.video]))['format']['duration']);Path(a.output).write_text(json.dumps(result,separators=(',',':')))
 print(json.dumps({'frames':count,'actors':{k:{'poses':len(v),'fitted':sum(p['quality']==1 for p in v)}for k,v in tracks.items()},'bytes':Path(a.output).stat().st_size}))
if __name__=='__main__':main()
